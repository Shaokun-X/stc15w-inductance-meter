static bool display_begin(unsigned char control)
{
    if (!i2c_start())
    {
        return false;
    }
    if (!i2c_write_byte(display_address << 1) || !i2c_write_byte(control))
    {
        i2c_stop();
        return false;
    }
    return true;
}

static bool display_probe(unsigned char address)
{
    bool acknowledged;

    if (!i2c_start())
    {
        return false;
    }
    acknowledged = i2c_write_byte(address << 1);
    i2c_stop();
    return acknowledged;
}

static void display_command(unsigned char command)
{
    if (display_begin(SSD1306_CONTROL_COMMAND))
    {
        i2c_write_byte(command);
        i2c_stop();
    }
}

static void display_command_pair(unsigned char command, unsigned char value)
{
    if (display_begin(SSD1306_CONTROL_COMMAND))
    {
        i2c_write_byte(command);
        i2c_write_byte(value);
        i2c_stop();
    }
}

static void display_set_position(unsigned char page, unsigned char column)
{
    display_command(0xb0 | page);
    display_command(0x00 | (column & 0x0f));
    display_command(0x10 | (column >> 4));
}

static void display_clear_page(unsigned char page)
{
    unsigned char column;

    display_set_position(page, 0);
    if (!display_begin(SSD1306_CONTROL_DATA))
    {
        return;
    }
    for (column = 0; column < SSD1306_WIDTH; column++)
    {
        i2c_write_byte(0x00);
    }
    i2c_stop();
}

static void display_write_character(char character)
{
    unsigned char column;
    unsigned char index;
    unsigned char code = (unsigned char)character;

    if (code == DISPLAY_CHAR_MU)
    {
        index = 96;
    }
    else if (code < ' ' || code > 0x7f)
    {
        index = '?' - ' ';
    }
    else
    {
        index = code - ' ';
    }
    for (column = 0; column < 5; column++)
    {
        i2c_write_byte(font[index][column]);
    }
    i2c_write_byte(0x00);
}

static void display_row(unsigned char page, const char *text, unsigned char offset)
{
    unsigned char position = offset;

    display_clear_page(page);
    if (text == 0 || offset >= DISPLAY_COLUMNS)
    {
        return;
    }

    display_set_position(page, offset * 6);
    if (!display_begin(SSD1306_CONTROL_DATA))
    {
        return;
    }
    while (*text != '\0' && *text != '\n' && position < DISPLAY_COLUMNS)
    {
        display_write_character(*text++);
        position++;
    }
    i2c_stop();
}

void display_init(void)
{
    i2c_init();
    delay_ms(100);

    if (display_probe(SSD1306_ADDRESS_PRIMARY))
    {
        display_address = SSD1306_ADDRESS_PRIMARY;
    }
    else if (display_probe(SSD1306_ADDRESS_SECONDARY))
    {
        display_address = SSD1306_ADDRESS_SECONDARY;
    }

    display_command(0xae);
    display_command_pair(0xd5, 0x80);
    display_command_pair(0xa8, 0x1f);
    display_command_pair(0xd3, 0x00);
    display_command(0x40);
    display_command_pair(0x8d, 0x14);
    display_command_pair(0x20, 0x02);
    display_command(0xa1);
    display_command(0xc8);
    display_command_pair(0xda, 0x02);
    display_command_pair(0x81, 0x8f);
    display_command_pair(0xd9, 0xf1);
    display_command_pair(0xdb, 0x40);
    display_command(0xa4);
    display_command(0xa6);
    display_clear();
    display_command(0xaf);
}

void display_clear(void)
{
    unsigned char page;

    for (page = 0; page < SSD1306_PAGES; page++)
    {
        display_clear_page(page);
    }
}

void display_top(const char *text, unsigned char offset)
{
    display_row(0, text, offset);
}

void display_bottom(const char *text, unsigned char offset)
{
    display_row(1, text, offset);
}

void display_text(const char *text)
{
    unsigned char page = 0;
    unsigned char position;

    display_clear();
    while (text != 0 && *text != '\0' && page < SSD1306_PAGES)
    {
        display_set_position(page, 0);
        if (!display_begin(SSD1306_CONTROL_DATA))
        {
            return;
        }

        position = 0;
        while (*text != '\0' && *text != '\n' && position < DISPLAY_COLUMNS)
        {
            display_write_character(*text++);
            position++;
        }
        i2c_stop();

        if (*text == '\n')
        {
            text++;
        }
        page++;
    }
}
